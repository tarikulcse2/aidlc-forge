#!/usr/bin/env bash
# Generate the traceability matrix (stories -> tests) as Markdown on stdout.
#   bash trace.sh [project_dir] > docs/traceability.md
# Stories:  "## US-NNN Title" headings in docs/baseline/stories.md and in the request.md of every CR that isn't closed.
#           Acceptance criteria are table rows starting with "| ACn |". Legacy tests are mapped with "Covered by: A, B".
# Tests:    names like US006_<Behaviour> or US006_AC04_<Behaviour> under `test_dirs`.

. "$(dirname "$0")/lib.sh"
cd "$(to_posix "${1:-${CLAUDE_PROJECT_DIR:-$PWD}}")" || exit 1
cfg=".aidlc/config.yaml"
prefix="$(cfg_get "$cfg" story_prefix)"; [ -n "$prefix" ] || prefix="US"
tdirs="$(cfg_get "$cfg" test_dirs)"; [ -n "$tdirs" ] || tdirs="$(cfg_get "$cfg" code_dirs)"; [ -n "$tdirs" ] || tdirs="."
exts="$(cfg_get "$cfg" code_exts)"

include=()
for e in $exts; do include+=("--include=*.$e"); done
grep_tests() { # shellcheck disable=SC2086
  grep -r "${include[@]}" --exclude-dir=bin --exclude-dir=obj --exclude-dir=node_modules --exclude-dir=.git "$@" $tdirs 2>/dev/null
}

# 1. Story sources: the baseline plus open CRs
sources=()
[ -f docs/baseline/stories.md ] && sources+=("docs/baseline/stories.md|baseline")
while IFS= read -r d; do
  [ -f "$d/request.md" ] || continue
  [ "$(cfg_get "$d/state.yaml" status)" = "closed" ] && continue
  cr="$(cr_label "$d/state.yaml")"
  sources+=("$d/request.md|${cr:-$(basename "$d")}")
done < <(cr_dirs .)

declare -A title src acs cov
order=()
for s in "${sources[@]}"; do
  file="${s%%|*}"; label="${s##*|}"
  while IFS=$'\t' read -r id t n c; do
    [ -n "$id" ] || continue
    if [ -z "${title[$id]+x}" ]; then order+=("$id"); title[$id]="$t"; src[$id]="$label"; acs[$id]=$n; cov[$id]="$c"
    else
      src[$id]="${src[$id]}, $label"
      [ "$n" -gt "${acs[$id]}" ] && acs[$id]=$n
      [ -n "$c" ] && cov[$id]="${cov[$id]:+${cov[$id]},}$c"
    fi
  done < <(tr -d '\r' < "$file" | awk -v prefix="$prefix" '
    function flush() { if (id != "") printf "%s\t%s\t%d\t%s\n", id, title, n, cov; id = "" }
    BEGIN { re = "^#+[ \t]+" prefix "-[0-9]+" }
    /^#/ {
      flush()
      if (match($0, re)) {
        id = substr($0, 1, RLENGTH); sub(/^#+[ \t]+/, "", id)
        title = substr($0, RLENGTH + 1)
        gsub(/\*\([^)]*\)\*/, "", title); gsub(/\|/, "/", title); gsub(/^[ \t:-]+|[ \t]+$/, "", title)
        n = 0; cov = ""
      }
      next
    }
    id != "" && /^\|[ \t]*AC[0-9]+[ \t]*\|/ { n++ }
    id != "" && /Covered by:/ { line = $0; sub(/.*Covered by:[ \t]*/, "", line); gsub(/[ \t`]/, "", line); cov = (cov == "" ? line : cov "," line) }
    END { flush() }')
done

# 2. Tests named after stories
all_tests="$(grep_tests -hoE "\b${prefix}[0-9]+_[A-Za-z0-9_]*" | sort -u)"

# 3. Table
rows=""; with=0; without=0; partial=0
for id in $(printf '%s\n' "${order[@]}" | sort -t- -k2,2n); do
  key="${id//-/}"
  named="$(printf '%s\n' "$all_tests" | grep -c "^${key}_")"
  ac_cov="$(printf '%s\n' "$all_tests" | grep -oE "^${key}_AC[0-9]+" | sort -u | grep -c .)"
  legacy=0; missing=""
  IFS=',' read -ra names <<< "${cov[$id]}"
  for nm in "${names[@]}"; do
    [ -n "$nm" ] || continue
    if grep_tests -qw "$nm"; then legacy=$((legacy + 1)); else missing="${missing:+$missing, }$nm"; fi
  done
  total=$((named + legacy))
  ac_text="–"; [ "$ac_cov" -gt 0 ] && ac_text="$ac_cov/${acs[$id]}"
  if [ "$total" -eq 0 ]; then status="❌ no tests"; without=$((without + 1))
  elif [ "$ac_cov" -gt 0 ] && [ "$ac_cov" -lt "${acs[$id]}" ]; then status="🟡 partial"; partial=$((partial + 1))
  else status="✅"; with=$((with + 1)); fi
  [ -n "$missing" ] && status="$status (missing: $missing)"
  rows+="| $id | ${title[$id]} | ${src[$id]} | ${acs[$id]} | $total | $ac_text | $status |"$'\n'
done

orphans=""
for k in $(printf '%s\n' "$all_tests" | grep -oE "^${prefix}[0-9]+" | sort -u); do
  id="${prefix}-${k#"$prefix"}"
  [ -n "${title[$id]+x}" ] || orphans="${orphans:+$orphans, }$k"
done

echo "# Traceability"
echo
echo "Generated by the aidlc-forge plugin (\`scripts/trace.sh\`) on $(date -u +%Y-%m-%d). Don't edit this file by hand."
echo
echo "| Story | Title | Source | ACs | Tests | ACs with tests | Status |"
echo "|---|---|---|---|---|---|---|"
printf '%s' "$rows"
echo
echo "**Summary:** ${#order[@]} stories: $with ✅, $partial 🟡 partial, $without ❌ without tests. $(printf '%s\n' "$all_tests" | grep -c .) story-named tests."
[ -n "$orphans" ] && echo "**Tests naming unknown stories:** $orphans"
echo
echo "_\"ACs with tests\" counts only tests named \`USnnn_ACk_...\`; other tests count toward the story only._"
